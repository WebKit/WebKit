shouldBe("\u{1F600}\u{1F600}".match(/\u{1F600}(?<=\u{1F600})/gu), ["\u{1F600}", "\u{1F600}"]);
shouldBe(matchOf(/(?<=[^a])b/gu, "\u{1F600}b", 1), [2, "b"]);
shouldBe(matchOf(/(?<=(.))\uDE00/su, "\u{1F600}" + trail), [2, trail, "\u{1F600}"]);

{
    let re = /(?<=([^x]{2}))x/u;
    shouldBe(matchOf(re, "abx"), [2, "x", "ab"]);
    shouldBe(matchOf(re, "a\u{1F600}x"), [3, "x", "a\u{1F600}"]);
    shouldBe(matchOf(re, "\u{1F600}x"), null);
    shouldBe(matchOf(re, "bx"), null);
    let re2 = /(?<=\u{1F600}|ab)x/u;
    shouldBe(matchOf(re2, "abx"), [2, "x"]);
    shouldBe(matchOf(re2, "\u{1F600}x"), [2, "x"]);
    shouldBe(matchOf(re2, "ax"), null);
    shouldBe(re.test("a\u{1F600}x"), true);
    shouldBe(re.test("abx"), true);
    shouldBe(re.test("\u{1F600}x"), false);
}
shouldBe(/(?<=(.)\u{1F600})x/su.test("a\u{1F600}x"), true);
shouldBe(/(?<=(.)\u{1F600})x/su.test("\u{1F600}x"), false);
shouldBe(/(?<=(b.{2}|c.|.))x/su.test("\u{1F600}\u{1F600}x"), true);
shouldBe(/(?<=\u{1F600}([^x]*))x/u.test("\u{1F600}\u{1F600}" + trail + "x"), true);
shouldBe(/(?<=\u{1F600}([^x]*))x/u.test("\u{1F601}" + trail + "x"), false);
shouldBe(/(?<=(a)(\u{1F600})(b)(\u{1F601}{2})(c))x/u.test("a\u{1F600}b\u{1F601}\u{1F601}cx"), true);
shouldBe(/(?<=(a)(\u{1F600})(b)(\u{1F601}{2})(c))x/u.test("a\u{1F600}b\u{1F601}\u{1F600}cx"), false);

for (let i = 0; i < 200; ++i) {
    shouldBe(matchOf(/(?<=\u{1F600}([^x]*))x/u, "a\u{1F600}\u{1F600}x"), [5, "x", "\u{1F600}"]);
    shouldBe(matchOf(/(?<=([a\u{1F600}]{3}))x/u, "\u{1F600}\u{1F600}ax"), [5, "x", "\u{1F600}\u{1F600}a"]);
    shouldBe(matchOf(/(?<=(\u{1F600}+?))x/u, "\u{1F600}\u{1F600}x"), [4, "x", "\u{1F600}"]);
    shouldBe(matchOf(/(?<=[\u{1F600}-\u{1F60F}])x/u, i & 1 ? "\u{1F600}x" : trail + "x"), i & 1 ? [2, "x"] : null);
}
