TEST(HEVCBitstreamParser, ReportsNoQpBeforeAnyParsing)
{
    HEVCBitstreamParser parser;
    EXPECT_FALSE(parser.lastSliceQP().has_value());
}

TEST(HEVCBitstreamParser, ReportsNoQpAfterParsingOnlyParameterSets)
{
    HEVCBitstreamParser parser;
    parser.parseBitstream(std::span { kH265VpsSpsPps });
    EXPECT_FALSE(parser.lastSliceQP().has_value());
}

TEST(HEVCBitstreamParser, ReportsQpForImageSlices)
{
    HEVCBitstreamParser parser;
    parser.parseBitstream(std::span { kH265BitstreamChunk });
    auto qp = parser.lastSliceQP();
    ASSERT_TRUE(qp.has_value());
    EXPECT_EQ(*qp, 34);

    // Parsing an additional slice on the same (already-known) SPS/PPS updates the QP.
    parser.parseBitstream(std::span { kH265BitstreamNextImageSliceChunk });
    qp = parser.lastSliceQP();
    ASSERT_TRUE(qp.has_value());
    EXPECT_EQ(*qp, 36);
}

TEST(HEVCBitstreamParser, ReportsQpFromShortTermReferencePicSetSlice)
{
    HEVCBitstreamParser parser;
    parser.parseBitstream(std::span { kH265SliceStrChunk });
    auto qp = parser.lastSliceQP();
    ASSERT_TRUE(qp.has_value());
    EXPECT_EQ(*qp, 33);
}

TEST(HEVCBitstreamParser, ReportsQpWithPredWeightTable)
{
    HEVCBitstreamParser parser;
    parser.parseBitstream(std::span { kH265BitstreamWithPredWeightTable });
    auto qp = parser.lastSliceQP();
    ASSERT_TRUE(qp.has_value());
    EXPECT_EQ(*qp, 34);
}

TEST(HEVCBitstreamParser, RejectsOutOfRangeQp)
{
    HEVCBitstreamParser lowParser;
    lowParser.parseBitstream(std::span { kH265BitstreamInvalidQPChunkLow });
    EXPECT_FALSE(lowParser.lastSliceQP().has_value());

    HEVCBitstreamParser highParser;
    highParser.parseBitstream(std::span { kH265BitstreamInvalidQPChunkHigh });
    EXPECT_FALSE(highParser.lastSliceQP().has_value());
}

