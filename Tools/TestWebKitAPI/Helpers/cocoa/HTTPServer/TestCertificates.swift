enum TestCertificates {
    static var certificate: SecCertificate {
        // The data is a literal, so guaranteed to be valid.
        // swift-format-ignore: NeverForceUnwrap
        SecCertificateCreateWithData(nil, certificateData as CFData)!
    }

    static var identity: SecIdentity {
        makeIdentity(privateKey: privateKeyData, certificate: certificateData)
    }

    static var identity2: SecIdentity {
        makeIdentity(privateKey: privateKeyData2, certificate: certificateData2)
    }
}

extension TestCertificates {
    fileprivate static func makeIdentity(privateKey: Data, certificate: Data) -> SecIdentity {
        let pkcs8HeaderLength = 26
        let attributes: [CFString: Any] = [
            kSecAttrKeyType: kSecAttrKeyTypeRSA,
            kSecAttrKeyClass: kSecAttrKeyClassPrivate,
            kSecAttrKeySizeInBits: 4096,
        ]

        guard let key = SecKeyCreateWithData(privateKey.dropFirst(pkcs8HeaderLength) as CFData, attributes as CFDictionary, nil) else {
            fatalError("Could not create test private key")
        }

        guard let certificate = SecCertificateCreateWithData(nil, certificate as CFData) else {
            fatalError("Could not create test certificate")
        }

        // The internal SDK declares SecIdentityCreate without audited ownership for Swift clients,
        // so Swift imports it as returning an Unmanaged value, while the public SDK imports it as
        // returning an owned value.
        #if USE_APPLE_INTERNAL_SDK
        return unsafe SecIdentityCreate(kCFAllocatorDefault, certificate, key).takeRetainedValue()
        #else
        // Guaranteed to be non-nil because the certificate and key are guaranteed to be valid.
        // swift-format-ignore: NeverForceUnwrap
        return SecIdentityCreate(kCFAllocatorDefault, certificate, key)!
        #endif
