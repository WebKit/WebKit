from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class UnclaimedShard:
    """Tests a worker was asked to run but could not, because its device was unusable.

    Returned instead of results so the tests go back around to a worker which has a device, rather than being recorded
    as failures they never had. Layout and API tests both do this, so they share it."""

    tests: List = field(default_factory=list)
    name: Optional[str] = None
