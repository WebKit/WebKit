import argparse
import json
from pathlib import Path


def parse_arguments():
    parser = argparse.ArgumentParser(description=(
        "Generate the set of WebDriver BiDi command names declared in "
        "WebKit protocol schemas."
    ))
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("protocols", nargs="+", type=Path)
    return parser.parse_args()


def command_names(protocol_paths):
    names = set()
    for protocol_path in protocol_paths:
        with protocol_path.open(encoding="utf-8") as protocol_file:
            protocol = json.load(protocol_file)

        exposed_as = protocol.get("exposedAs")
        if not isinstance(exposed_as, str):
            raise ValueError(f"Missing string 'exposedAs' in {protocol_path}")

        for command in protocol.get("commands", []):
            command_name = command.get("name")
            if not isinstance(command_name, str):
                raise ValueError(f"Missing string command name in {protocol_path}")

            qualified_name = f"{exposed_as}.{command_name}"
            if qualified_name in names:
                raise ValueError(f"Duplicate command name: {qualified_name}")
            names.add(qualified_name)

    return sorted(names)


def generate_header(names):
    lines = [
        "// This file is generated by generate-webdriver-bidi-command-names.py.",
        "",
        "#pragma once",
        "",
        "#include <wtf/SortedArrayMap.h>",
        "#include <wtf/StdLibExtras.h>",
        "",
        "namespace WebDriver {",
        "",
        "static constexpr SortedArraySet bidiSessionBoundCommandNames { "
        "WTF::toArray<ComparableASCIILiteral>({",
    ]
    lines.extend(f'    "{name}"_s,' for name in names)
    lines.extend([
        "}) };",
        "",
        "} // namespace WebDriver",
        "",
    ])
    return "\n".join(lines)


def main():
    arguments = parse_arguments()
    header = generate_header(command_names(arguments.protocols))
    arguments.output.write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
