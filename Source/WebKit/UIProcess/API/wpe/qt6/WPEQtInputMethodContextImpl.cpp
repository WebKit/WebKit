void wpe_get_cursor_rect(WPEInputMethodContext* ctx, int* x, int* y, int* width, int* height)
{
    auto* priv = WPE_INPUT_METHOD_CONTEXT_QT(ctx)->priv;
    if (x)
        *x = priv->cursorRect.x;
    if (y)
        *y = priv->cursorRect.y;
    if (width)
        *width = priv->cursorRect.width;
    if (height)
        *height = priv->cursorRect.height;
}
