#pragma once

namespace WebCore {

// Identifies the reference value a UsedStyle getter resolves percentages against. Every
// reference is renderer-derived, so resolution is lazy (only computed when the value is
// actually a percentage) and the walk is not paid for fixed values. Callers that already
// hold the reference pass a LayoutUnit instead.
// UsedStyleProperties::resolveReferenceSize() maps these to a length using its renderer.
enum class ReferenceSize : uint8_t {
    ContainingBlockWidth,
};

} // namespace WebCore
